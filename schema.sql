CREATE DATABASE IF NOT EXISTS `portal_uup` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `portal_uup`;
SET NAMES utf8mb4;
DROP TABLE IF EXISTS `attachment_part`;
DROP TABLE IF EXISTS `attachment`;
DROP TABLE IF EXISTS `history`;
DROP TABLE IF EXISTS `appeal`;
DROP TABLE IF EXISTS `bulletin`;
DROP TABLE IF EXISTS `building`;
DROP TABLE IF EXISTS `precinct`;
DROP TABLE IF EXISTS `profile`;
DROP TABLE IF EXISTS `log`;
DROP TABLE IF EXISTS `rate_limit`;

CREATE TABLE `profile` (
    `id` int(11) NOT NULL AUTO_INCREMENT,
`name` varchar(100) NOT NULL,
`role` enum('citizen','officer','department_head','manager') NOT NULL,
`department_id` int(11) DEFAULT NULL,
`residence` varchar(150) DEFAULT NULL,
`login` varchar(50) DEFAULT NULL,
`password` varchar(255) DEFAULT NULL,
PRIMARY KEY (`id`),
UNIQUE KEY `login` (`login`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `precinct` (
    `id` int(11) NOT NULL AUTO_INCREMENT,
`district` varchar(150) NOT NULL,
`name` varchar(150) NOT NULL,
`officer` int(11) DEFAULT NULL,
`hours` varchar(100) NOT NULL,
`phone` varchar(30) DEFAULT NULL,
`address` varchar(200) DEFAULT NULL,
`lat` decimal(10,8) DEFAULT NULL,
`lng` decimal(11,8) DEFAULT NULL,
`is_department` tinyint(1) DEFAULT 0,
PRIMARY KEY (`id`),
KEY `officer` (`officer`),
CONSTRAINT `precinct_ibfk_1` FOREIGN KEY (`officer`) REFERENCES `profile` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `building` (
    `address` varchar(150) NOT NULL,
`precinct_id` int(11) NOT NULL,
`fias_id` char(36) DEFAULT NULL,
PRIMARY KEY (`address`),
KEY `precinct_id` (`precinct_id`),
CONSTRAINT `building_ibfk_1` FOREIGN KEY (`precinct_id`) REFERENCES `precinct` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `appeal` (
    `id` int(11) NOT NULL AUTO_INCREMENT,
`citizen` int(11) NOT NULL,
`category` varchar(60) NOT NULL,
`subject` varchar(180) NOT NULL,
`body` text NOT NULL,
`address` varchar(150) NOT NULL,
`precinct_id` int(11) DEFAULT NULL,
`officer` int(11) DEFAULT NULL,
`status` enum('manual','assigned','work','department_review','manager_review','review','closed') NOT NULL DEFAULT 'manual',
`created` datetime DEFAULT current_timestamp(),
`due` date NOT NULL,
`draft` text DEFAULT NULL,
`rating` tinyint(1) DEFAULT NULL,
`feedback` text DEFAULT NULL,
PRIMARY KEY (`id`),
KEY `precinct_id` (`precinct_id`),
KEY `officer` (`officer`, `status`),
KEY `citizen` (`citizen`, `created`),
CONSTRAINT `appeal_ibfk_1` FOREIGN KEY (`citizen`) REFERENCES `profile` (`id`),
CONSTRAINT `appeal_ibfk_2` FOREIGN KEY (`precinct_id`) REFERENCES `precinct` (`id`),
CONSTRAINT `appeal_ibfk_3` FOREIGN KEY (`officer`) REFERENCES `profile` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `history` (
    `id` int(11) NOT NULL AUTO_INCREMENT,
`appeal_id` int(11) NOT NULL,
`actor` int(11) NOT NULL,
`event` varchar(255) NOT NULL,
`created` datetime DEFAULT current_timestamp(),
PRIMARY KEY (`id`),
KEY `appeal_id` (`appeal_id`),
KEY `actor` (`actor`),
CONSTRAINT `history_ibfk_1` FOREIGN KEY (`appeal_id`) REFERENCES `appeal` (`id`) ON DELETE CASCADE,
CONSTRAINT `history_ibfk_2` FOREIGN KEY (`actor`) REFERENCES `profile` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `attachment` (
    `id` int(11) NOT NULL AUTO_INCREMENT,
`appeal_id` int(11) NOT NULL,
`name` varchar(180) NOT NULL,
`mime` varchar(80) NOT NULL,
PRIMARY KEY (`id`),
KEY `appeal_id` (`appeal_id`),
CONSTRAINT `attachment_ibfk_1` FOREIGN KEY (`appeal_id`) REFERENCES `appeal` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `attachment_part` (
    `attachment_id` int(11) NOT NULL,
`part_no` int(11) NOT NULL,
`content` mediumblob NOT NULL,
PRIMARY KEY (`attachment_id`, `part_no`),
CONSTRAINT `attachment_part_ibfk_1` FOREIGN KEY (`attachment_id`) REFERENCES `attachment` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `bulletin` (
    `id` int(11) NOT NULL AUTO_INCREMENT,
`title` varchar(180) NOT NULL,
`body` text NOT NULL,
`author` int(11) NOT NULL,
`created` datetime DEFAULT current_timestamp(),
PRIMARY KEY (`id`),
KEY `author` (`author`),
CONSTRAINT `bulletin_ibfk_1` FOREIGN KEY (`author`) REFERENCES `profile` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `log` (
    `id` INT AUTO_INCREMENT PRIMARY KEY,
`created` DATETIME DEFAULT CURRENT_TIMESTAMP,
`level` ENUM('info','warning','error') NOT NULL,
`user_id` INT NULL,
`action` VARCHAR(100) NOT NULL,
`details` TEXT NULL,
`ip` VARCHAR(45) NULL,
KEY `user_id` (`user_id`),
KEY `created` (`created`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `rate_limit` (
    `ip` VARCHAR(45) PRIMARY KEY,
`attempts` INT DEFAULT 0,
`blocked_until` DATETIME DEFAULT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

